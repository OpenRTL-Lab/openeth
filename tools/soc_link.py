"""Connect a generated ChipTop to the public MAC, frame buffers and RGMII."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def ports(text):
    text = re.sub(r'/\*.*?\*/|//[^\n]*', '', text, flags=re.S)
    found = re.search(r'\bmodule\s+ChipTop\s*\((.*?)\);', text, re.S)
    if not found:
        raise ValueError('expected a non-parameterized ANSI ChipTop')
    result = {}
    direction, width = None, ''
    for item in found[1].split(','):
        m = re.fullmatch(r'\s*(?:(input|output)\s+)?(?:wire\s+|logic\s+)?'
                         r'(\[\d+:\d+\]\s*)?(\w+)\s*', item)
        if not m:
            raise ValueError('unsupported port declaration: ' + item)
        if m[1]:
            direction, width = m[1], (m[2] or '').strip()
        elif m[2]:
            width = m[2].strip()
        if direction is None or m[3] in result:
            raise ValueError('missing direction or duplicate port')
        result[m[3]] = (direction, width)
    return result


def contract(p):
    expected = {
        'clock_uncore': ('input', ''), 'reset_io': ('input', ''),
        'eth_0_mac_speed': ('input', '[1:0]'),
        'axi4_mem_0_bits_w_bits_data': ('output', '[511:0]'),
        'axi4_mem_0_bits_r_bits_data': ('input', '[511:0]'),
    }
    for direction in ('tx', 'rx'):
        for field, width in (('tdata', '[7:0]'), ('tvalid', ''), ('tready', ''), ('tlast', '')):
            d = 'input' if (direction == 'tx') == (field == 'tready') else 'output'
            expected['eth_0_' + direction + '_axis_' + field] = (d, width)
        for field, width in (('ready', ''), ('valid', ''), ('bits_data', '[63:0]'),
                             ('bits_keep', '[7:0]'), ('bits_last', ''), ('bits_error', '')):
            d = 'input' if (direction == 'tx') == (field == 'ready') else 'output'
            expected['opennic_' + direction + '_' + field] = (d, width)
    for field in ('rx_bad_fcs', 'rx_bad_frame', 'rx_good_frame',
                  'tx_bad_frame', 'tx_good_frame', 'tx_underflow'):
        expected['eth_0_mac_' + field] = ('input', '')
    for name in p:
        if name.startswith(('opennic_', 'eth_0_mac_')) and name not in expected:
            raise ValueError('unexpected internal port: ' + name)
    for name, signature in expected.items():
        if p.get(name) != signature:
            raise ValueError('port contract mismatch: ' + name)
    if len(p) != 102:
        raise ValueError('expected the complete 102-port ChipTop')


def emit(p):
    contract(p)
    hidden = {n for n in p if n.startswith('opennic_')}
    hidden |= {'eth_0_mac_speed', 'eth_0_tx_axis_tdata', 'eth_0_tx_axis_tvalid',
               'eth_0_tx_axis_tready', 'eth_0_tx_axis_tlast', 'eth_0_rx_axis_tdata',
               'eth_0_rx_axis_tvalid', 'eth_0_rx_axis_tready', 'eth_0_rx_axis_tlast'}
    hidden |= {n for n in p if n.startswith('eth_0_mac_') and n != 'eth_0_mac_speed'}
    extra = [('input', '', 'gtx_clk'), ('input', '', 'gtx_clk90'),
             ('input', '', 'gtx_reset'), ('input', '', 'phy_rxc'),
             ('input', '[3:0]', 'phy_rxd'), ('input', '', 'phy_rx_ctrl'),
             ('output', '', 'phy_txc'), ('output', '[3:0]', 'phy_txd'),
             ('output', '', 'phy_tx_ctrl')]
    external = [(d, w, n) for n, (d, w) in p.items() if n not in hidden] + extra
    lines = ['// Generated by tools/soc_link.py; digital integration only.',
             '// SPDX-License-Identifier: MIT',
             'module OpenEthSoC #(parameter TARGET = "XILINX") (',
             ',\n'.join('  ' + d + ' wire ' + (w + ' ' if w else '') + n
                        for d, w, n in external), ');']
    for name in sorted(hidden):
        _, width = p[name]
        lines.append('  wire ' + (width + ' ' if width else '') + name + ';')
    # The management peripheral has no packet data plane in this configuration.
    for name in sorted(hidden):
        if p[name][0] == 'input' and not name.startswith('opennic_') and name != 'eth_0_mac_speed':
            lines.append('  assign ' + name + " = '0;")
    lines += ['  ChipTop soc (',
              ',\n'.join('    .' + n + '(' + n + ')' for n in p), '  );']
    link = {
        'nic_clk': 'clock_uncore', 'sys_reset': 'reset_io',
        'gtx_clk': 'gtx_clk', 'gtx_clk90': 'gtx_clk90', 'gtx_reset': 'gtx_reset',
        'phy_rxc': 'phy_rxc', 'phy_rxd': 'phy_rxd', 'phy_rx_ctrl': 'phy_rx_ctrl',
        'phy_txc': 'phy_txc', 'phy_txd': 'phy_txd', 'phy_tx_ctrl': 'phy_tx_ctrl',
        'speed': 'eth_0_mac_speed', 'tx_activity_nic': '', 'rx_activity_nic': '',
        'tx_overflow_nic': '', 'rx_overflow_nic': '',
    }
    for direction in ('tx', 'rx'):
        for field in ('ready', 'valid', 'data', 'keep', 'last', 'error'):
            source = field if field in ('ready', 'valid') else 'bits_' + field
            link[direction + '_' + field] = 'opennic_' + direction + '_' + source
    lines += ['  OpenEthBoardLink #(.TARGET(TARGET)) ethernet (',
              ',\n'.join('    .' + n + '(' + v + ')' for n, v in link.items()),
              '  );', 'endmodule', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--soc', type=Path, required=True, help='generated RTL directory')
    parser.add_argument('--out', type=Path, required=True, help='new output directory')
    parser.add_argument('--lint', action='store_true', help='lint the complete digital hierarchy with generic DDR I/O models')
    parser.add_argument('--verilator', default='verilator')
    args = parser.parse_args()
    top = args.soc / 'ChipTop.sv'
    output = emit(ports(top.read_text()))
    args.out.mkdir(parents=True)
    wrapper = args.out / 'OpenEthSoC.sv'
    wrapper.write_text(output)
    components = [
        'nic/integration/OpenEthBoardLink.sv', 'mac/rtl/OpenEthMac.sv',
        'rtl/mac/MacGmiiCore.sv', 'rtl/rgmii/RgmiiDigital.sv',
        'rgmii/rtl/OpenEthRgmiiPairs.sv', 'rgmii/rtl/OpenEthRgmii1G.sv',
        *['buffer/rtl/' + n for n in ('openeth_cdc.sv', 'openeth_frame_fifo.sv',
                                     'openeth_stream_up.sv', 'openeth_stream_down.sv')],
        *['third_party/verilog-ethernet/' + n for n in ('iddr.v', 'oddr.v', 'ssio_ddr_in.v')],
    ]
    sources = [wrapper.resolve(), *sorted(args.soc.resolve().glob('*.sv')),
               *sorted(args.soc.resolve().glob('*.v')), *[ROOT / n for n in components]]
    for source in sources:
        if not source.is_file():
            raise ValueError('missing source: ' + source.name)
    (args.out / 'sources.f').write_text('\n'.join(str(p) for p in sources) + '\n')
    record = {
        'status': 0, 'top': 'OpenEthSoC', 'chiptop_ports': 102,
        'chiptop_sha256': hashlib.sha256(top.read_bytes()).hexdigest(),
        'wrapper_sha256': hashlib.sha256(wrapper.read_bytes()).hexdigest(),
        'hardware_access': False, 'structural_connection_only': True,
    }
    if args.lint:
        with (args.out / 'lint.log').open('w') as log:
            result = subprocess.run([args.verilator, '--lint-only', '--timing',
                '-Wno-fatal', '-GTARGET="GENERIC"', '--top-module', 'OpenEthSoC',
                '-f', str((args.out / 'sources.f').resolve())],
                stdout=log, stderr=subprocess.STDOUT)
        record['lint_exit_code'] = result.returncode
        record['status'] = int(result.returncode != 0)
        record['lint_log_sha256'] = hashlib.sha256((args.out / 'lint.log').read_bytes()).hexdigest()
    (args.out / 'link.json').write_text(json.dumps(record, indent=2) + '\n')
    if record['status']:
        raise SystemExit('digital hierarchy lint failed; inspect lint.log')
    print('OPENETH_SOC_LINK_PASS ports=102 streams=2')


if __name__ == '__main__':
    main()
