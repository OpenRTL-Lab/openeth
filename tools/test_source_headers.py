import contextlib
import io
import tempfile
from pathlib import Path
import unittest
from unittest.mock import patch
from source_headers import check, header, paths, private_material, sha, stamp
import json


class Headers(unittest.TestCase):
    def test_generic_private_material(self):
        cases = [b'/' + b'home/alice/work', b'/' + b'mnt/shared',
                 b'C:' + b'\\Users\\alice\\work',
                 b'10.' + b'23.45.67', b'10.' + b'23.45.',
                 b'192.' + b'168.2.3', b'172.' + b'20.2.3',
                 b'-----BEGIN ' + b'OPENSSH PRIVATE KEY-----',
                 b'Authorization:' + b' Bearer example-token',
                 b'ghp_' + b'x' * 36]
        for data in cases:
            with self.subTest(data=data):
                self.assertTrue(private_material(data))
        for data in [b'192.0.2.1', b'rtl/mac.sv', b'iperf-test.log',
                     Path(__file__).with_name('source_headers.py').read_bytes(),
                     Path(__file__).read_bytes()]:
            self.assertFalse(private_material(data))

    def test_checker_and_metadata_are_not_exempt(self):
        for name in ['tools/source_headers.py', 'PUBLIC_FILES.json',
                     'PUBLIC_FILES.json.license']:
            with self.subTest(name=name), tempfile.TemporaryDirectory() as temp:
                root = Path(temp)
                (root / 'tools').mkdir()
                checker = b'print(1)\n'
                (root / 'tools/source_headers.py').write_bytes(checker)
                coverage = {'files': [dict(path='tools/source_headers.py',
                    sha256=sha(checker), classification='legal')]}
                (root / 'PUBLIC_FILES.json').write_text(json.dumps(coverage))
                (root / 'PUBLIC_FILES.json.license').write_bytes(b'MIT\n')
                target = root / name
                target.write_bytes(target.read_bytes() + b'\n' + b'/' + b'home/alice/work\n')
                with self.assertRaisesRegex(ValueError, 'private material'):
                    check(root)

    def test_idempotent_and_preserves_shebang(self):
        for name, data in [('model.py', b'#!/usr/bin/env python3\nprint(1)\n'),
                           ('build.mill', b'//| mill-version: 1.1.7\npackage build\n'),
                           ('thing.sv', b'// Generated by CIRCT\nmodule thing; endmodule\n')]:
            output = stamp(name, data)
            self.assertEqual(stamp(name, output), output)
            self.assertIn(data.splitlines()[-1], output)
            self.assertEqual(output.split(header(name))[0] + output.split(header(name))[1], data)

    def test_duplicate_or_tampered_header_rejected(self):
        for bad in [header('bad.sv') + header('bad.sv'), header('other.sv'),
                    header('bad.sv').replace(b' MIT', b' MIT-tampered')]:
            with self.assertRaises(ValueError):
                stamp('bad.sv', bad)

    def test_exact_coverage_negative_controls(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            sample = stamp('sample.sv', b'module sample; endmodule\n')
            (root / 'sample.sv').write_bytes(sample)
            (root / 'PUBLIC_FILES.json').write_text(json.dumps({'files': [dict(path='sample.sv', sha256=sha(sample), classification='original-inline')]}))
            (root / 'PUBLIC_FILES.json.license').write_bytes(header('PUBLIC_FILES.json.license'))
            (root / 'unknown').write_text('unknown\n')
            with self.assertRaisesRegex(ValueError, 'unknown or missing'):
                check(root)
            (root / 'unknown').unlink()
            (root / 'sample.sv').write_bytes(sample + b'// changed\n')
            with self.assertRaisesRegex(ValueError, 'payload hash changed'):
                check(root)


if __name__ == '__main__':
    unittest.main()
